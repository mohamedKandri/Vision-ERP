export const DICTS: Record<Lang, Dict> = { fr, en, ar };
export const LANG_NAMES: Record<Lang, string> = { fr: "Français", ar: "العربية", en: "English" };

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s = DICTS[lang]?.[key] ?? fr[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function applyLang(lang: Lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
}

export const LangContext = createContext<Lang>("fr");
export function useT() {
  const lang = useContext(LangContext);
  return Object.assign((key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars), { lang });
}

/** Translate an API error code, falling back to the generic message. */
export function errorText(lang: Lang, e: unknown): string {
  const code = (e as { code?: string })?.code ?? "internal";
  if (code === "locked") return translate(lang, "locked", { s: (e as { retry_after_secs?: number }).retry_after_secs ?? 60 });
  if (code === "wrong_pin") return translate(lang, "wrong_pin");
  const key = `err_${code}` as Key;
  return key in fr ? translate(lang, key) : `${translate(lang, "err_internal")} (${(e as { message?: string })?.message ?? code})`;
}
